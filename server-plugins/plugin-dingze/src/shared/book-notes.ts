export function bookNote(code: string): BookNote | null {
  return BOOK_NOTES[code] ?? null;
}

/** The guide for where the user is: a sub-step of S2-01 or a zone of S2-03, else the table's own. */
export function taskGuide(code: string, where: { sub?: number | string | null; zone?: string | null } = {}): { title: string | null; guide: TaskGuide } | null {
  const note = BOOK_NOTES[code];
  if (!note?.guide) return null;
  const key = code === 'S2-01' ? String(where.sub ?? 1) : code === 'S2-03' ? (where.zone === 'paths' ? 'paths' : 'targets') : null;
  const part = key ? note.parts?.[key] : undefined;
  return part ? { title: part.title, guide: part.guide } : { title: null, guide: note.guide };
}
