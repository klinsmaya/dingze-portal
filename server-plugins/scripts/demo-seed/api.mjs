// API helper for the demo seed: signs users in and calls the dingze / NocoBase API.
// Secrets never live in the repo: passwords are read from $DINGZE_SECRETS_DIR/<user>.pw, the admin
// token from $NOCOBASE_TOKEN (or $DINGZE_SECRETS_DIR/admin.token). Nothing secret is printed.
import fs from 'node:fs';

export const BASE = process.env.DINGZE_API_URL || 'https://ziqu.aihupo.cn/api';
export const SECRETS = process.env.DINGZE_SECRETS_DIR;
if (!SECRETS) throw new Error('set DINGZE_SECRETS_DIR to a private directory holding <user>.pw files');
/** Generated ids (org units, users, project 3) shared between setup.mjs and seed.ts. */
export const IDS_FILE = `${SECRETS}/demo-ids.json`;
const tokens = new Map();

async function retry(fn) {
  for (let i = 0; i < 4; i++) {
    try { return await fn(); } catch (e) { if (i === 3) throw e; await new Promise((r) => setTimeout(r, 1500 * (i + 1))); }
  }
}

export async function token(user) {
  if (user === 'admin') return (process.env.NOCOBASE_TOKEN || fs.readFileSync(`${SECRETS}/admin.token`, 'utf8')).trim();
  if (tokens.has(user)) return tokens.get(user);
  const password = fs.readFileSync(`${SECRETS}/${user}.pw`, 'utf8').trim();
  const j = await retry(async () => (await fetch(`${BASE}/auth:signIn`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Authenticator': 'basic' }, body: JSON.stringify({ account: user, password }) })).json());
  if (!j?.data?.token) throw new Error(`sign-in failed for ${user}`);
  tokens.set(user, j.data.token);
  return j.data.token;
}

/** Keep a password generated by createUser; mode 600, never printed. */
export function remember(user, password) {
  fs.writeFileSync(`${SECRETS}/${user}.pw`, password, { mode: 0o600 });
}

/** call(user, 'dingze:action?x=1', body?, { space }) → { status, data } */
export async function call(user, path, body, opts = {}) {
  const headers = { Authorization: `Bearer ${await token(user)}`, 'Content-Type': 'application/json' };
  if (opts.space) headers['x-spaces'] = opts.space;
  return retry(async () => {
    const r = await fetch(`${BASE}/${path}`, { method: body !== undefined && body !== null ? 'POST' : 'GET', headers, body: body !== undefined && body !== null ? JSON.stringify(body) : undefined });
    const text = await r.text();
    let j; try { j = JSON.parse(text); } catch { j = { raw: text.slice(0, 200) }; }
    return { status: r.status, data: j?.data ?? j };
  });
}

/** Throws unless 2xx; returns data. */
export async function ok(user, path, body, opts) {
  const r = await call(user, path, body, opts);
  if (r.status < 200 || r.status >= 300) throw new Error(`${user} ${path} → ${r.status} ${JSON.stringify(r.data).slice(0, 300)}`);
  return r.data;
}
